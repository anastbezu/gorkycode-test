"""Прогрев поиска при старте сервера: модель в памяти, векторы стартового набора в базе.

Без прогрева первый поиск «похожих» после деплоя ждёт загрузку модели, а первый в жизни
базы — ещё и векторы 376 названий стартового набора: замер в контейнере на 1 ядре —
импорт PyTorch и sentence-transformers 9,5 с, загрузка модели 1,1 с, 376 векторов 6,3 с.
Прогрев делает это в фоне сразу после старта, запросы его не ждут.
"""

from sqlalchemy.orm import Session

from services.bootstrap import read_dataset

from . import embeddings, vectors


def warm_up(db: Session) -> int:
    """Загрузить модель и досчитать векторы названий стартового набора.

    Возвращает, сколько векторов посчитано (0, если все уже были). Коммитит сам:
    вызывается отдельной сессией при старте, а не внутри реплики.
    """
    titles = sorted({row.text for row in read_dataset()})
    computed = vectors.ensure_vectors(db, titles)
    db.commit()
    # Векторы могли быть посчитаны раньше — модель всё равно загрузить, иначе её ждал бы
    # первый запрос.
    embeddings.embed_queries(["прогрев"])
    return computed
