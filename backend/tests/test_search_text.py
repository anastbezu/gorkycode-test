"""Уровень «точно» (`search.text`): правило «каждое значимое слово запроса есть в названии».

Без базы и без модели. Названия — из стартового датасета, с его искажёнными падежами.
"""

import pytest

from schemas import RecordType
from search.text import QueryWords, TitleWords, is_exact, words

MEETING, TASK, REMINDER = RecordType.MEETING, RecordType.TASK, RecordType.REMINDER


def exact(query: str, title: str, record_type: RecordType = TASK) -> bool:
    return is_exact(QueryWords(query), TitleWords(title), record_type)


@pytest.mark.parametrize(
    ("query", "title"),
    [
        ("созвон с юристами", "Созвон с юристом по договору"),  # одна основа: юрист
        ("позвонить Марии", "Позвонить Марией"),  # падеж имени: одна основа
        ("отправить Ольге", "Отправить смету Ольгой"),  # искажённый падеж датасета
        ("смета для Максима", "Согласовать смету с Максимом"),
        ("отчет", "Подготовить отчёт для Анны"),  # «е» вместо «ё»
        ("планёрка по CRM", "Провести планёрку по CRM"),
        ("Дмитрий бюджет", "Напомнить Дмитрию про бюджет"),
        # Основы Snowball разные (`серг` / `серге`, `ива` / `иван`) — совпадает словарная форма.
        ("позвонить Сергею", "Позвонить Сергеем"),
        ("встреча с Иван", "Встреча с Иваном по бюджету"),
        ("Алексей", "Согласовать отчёт с Алексеем"),
        ("Елена", "Отправить отчёт Еленой"),
        # Опечатка: слова нет в словаре, буквы почти те же.
        ("созвон с Севермо", "Созвон с Севером по CRM"),
    ],
)
def test_all_significant_words_found(query, title):
    assert exact(query, title)


@pytest.mark.parametrize(
    ("query", "title"),
    [
        # Названа другая тема — не та запись, даже если остальное совпало (нечёткое
        # сравнение всей фразы, как в OVOS, выбирало её — docs/modules/search.md).
        ("созвон с Севером по CRM", "Созвон с Севером по новому продукту"),
        ("отправить смету Анне", "Согласовать смету с Анной"),
        ("встреча с дизайнером", "Встреча с Иваном по дизайну сайта"),
        # Другая основа и разные буквы — для «точно» мало, это работа уровня «похожие».
        ("звонок Дмитрию", "Позвонить Дмитрием"),
        # Разные люди и компании — не одно слово ни по основе, ни по словарю.
        ("позвонить Марии", "Позвонить Марине"),
        ("созвон с Альфой", "Созвон с Альтаиром"),
        # Оба слова словарные и отличаются одной буквой — это разные слова, не опечатка.
        ("встреча с Виктором", "Подготовиться к встрече с Вектором"),
    ],
)
def test_missing_word_is_not_exact(query, title):
    assert not exact(query, title)


def test_type_word_matches_by_title_or_record_type():
    # Слова «задача» в названиях задач нет: «задачу про смету» — задача со «сметой».
    assert exact("задачу про смету", "Согласовать смету с Максимом", TASK)
    assert exact("задачу про CRM", "Напомнить Анной про CRM", REMINDER)  # «задачи» — и напоминания
    # «Встречу» — запись типа «встреча», даже если в названии «созвон».
    assert exact("встречу с Иваном", "Созвон с Иваном", MEETING)
    assert not exact("встречу с Иваном", "Встреча с Ольгой", MEETING)


def test_type_word_excludes_other_types():
    # «Отмени встречу с Алексеем по CRM», а есть только задача — это не она.
    assert not exact("встречу с Алексеем по CRM", "Обсудить CRM с Алексеем", TASK)
    assert not exact("задачу с Иваном", "Встреча с Иваном по бюджету", MEETING)
    assert not exact("напоминание Сергею", "Позвонить Сергеем", TASK)


def test_type_word_in_title_counts_whatever_the_type():
    # Слово есть в названии — оно совпало: «итоги встречи» — задача, но слово «встреча» в ней есть.
    assert exact("встречу", "Встреча с Ольгой", MEETING)
    assert exact("итоги встречи Марией", "Отправить итоги встречи Марией", TASK)


def test_only_type_word_finds_records_of_that_type():
    assert exact("встречу", "Созвон с Иваном", MEETING)
    assert not exact("встречу", "Позвонить Иваном", TASK)


def test_query_of_only_stop_words_matches_nothing():
    assert not exact("про по с", "Созвон с Иваном", MEETING)
    assert not exact("", "Созвон с Иваном", MEETING)


def test_words_keep_latin_and_digits():
    assert words("Созвон по CRM и 1С, ТЗ") == ["созвон", "по", "crm", "и", "1с", "тз"]
