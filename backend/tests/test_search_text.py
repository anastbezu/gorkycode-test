"""Уровень «точно» (`search.text`): правило «каждое значимое слово запроса есть в названии».

Без базы и без модели. Названия — из стартового датасета, с его искажёнными падежами.
"""

import pytest

from search.text import QueryWords, TitleWords, is_exact, words


def exact(query: str, title: str) -> bool:
    return is_exact(QueryWords(query), TitleWords(title))


@pytest.mark.parametrize(
    ("query", "title"),
    [
        ("созвон с юристами", "Созвон с юристом по договору"),  # одна основа: юрист
        ("позвонить Марии", "Позвонить Марией"),  # падеж имени: одна основа
        ("отправить Ольге", "Отправить смету Ольгой"),  # искажённый падеж датасета
        ("смета для Максима", "Согласовать смету с Максимом"),
        ("отчет", "Подготовить отчёт для Анны"),  # «е» вместо «ё»
        ("планёрка по CRM", "Провести планёрку по CRM"),
        ("Дмитрий бюджет", "Напомнить Дмитрию про бюджет"),
        # Основы Snowball разные (`серг` / `серге`, `ива` / `иван`) — совпадает словарная форма.
        ("позвонить Сергею", "Позвонить Сергеем"),
        ("встреча с Иван", "Встреча с Иваном по бюджету"),
        ("Алексей", "Согласовать отчёт с Алексеем"),
        ("Елена", "Отправить отчёт Еленой"),
    ],
)
def test_all_significant_words_found(query, title):
    assert exact(query, title)


@pytest.mark.parametrize(
    ("query", "title"),
    [
        # Названа другая тема — не та запись, даже если остальное совпало (нечёткое
        # сравнение всей фразы, как в OVOS, выбирало её — docs/modules/search.md).
        ("созвон с Севером по CRM", "Созвон с Севером по новому продукту"),
        ("отправить смету Анне", "Согласовать смету с Анной"),
        ("встреча с дизайнером", "Встреча с Иваном по дизайну сайта"),
        # Другая основа и разные буквы — для «точно» мало, это работа уровня «похожие».
        ("звонок Дмитрию", "Позвонить Дмитрием"),
        # Разные люди и компании — не одно слово ни по основе, ни по словарю.
        ("позвонить Марии", "Позвонить Марине"),
        ("созвон с Альфой", "Созвон с Альтаиром"),
    ],
)
def test_missing_word_is_not_exact(query, title):
    assert not exact(query, title)


def test_type_word_is_skipped_when_title_has_none():
    # В названиях задач слова «задача» нет: «задачу про смету» ищется как «смету».
    assert exact("задачу про смету", "Согласовать смету с Максимом")
    # Контракт: слово типа значимо, только если оно есть в названии.
    assert exact("встречу с Иваном", "Созвон с Иваном")
    assert not exact("встречу с Иваном", "Встреча с Ольгой")


def test_query_of_only_type_or_stop_words_matches_nothing():
    assert not exact("встречу", "Созвон с Иваном")
    assert not exact("про по с", "Созвон с Иваном")
    assert not exact("", "Созвон с Иваном")


def test_type_word_present_in_title_counts():
    # «встречу» есть в названии — значимое слово, и оно совпало.
    assert exact("встречу", "Встреча с Ольгой")


def test_words_keep_latin_and_digits():
    assert words("Созвон по CRM и 1С, ТЗ") == ["созвон", "по", "crm", "и", "1с", "тз"]
