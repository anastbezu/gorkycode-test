@pytest.mark.parametrize("case_id,text,expected", CASES, ids=[case[0] for case in CASES])
def test_live_date_interpretation(case_id, text, expected):
    try:
        action = asyncio.run(get_action(text, NOW, "Europe/Moscow"))
    except (openai.APIError, LLMConfigError) as exc:
        pytest.fail(f"{case_id}: {type(exc).__name__}, HTTP {getattr(exc, 'status_code', None)}",
                    pytrace=False)
    actual = action.model_dump(mode="json")
    for field, value in expected.items():
        assert actual.get(field) == value, (case_id, field, actual)
