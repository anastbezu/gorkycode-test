MANUAL = "проверяется руками в интерфейсе"


@dataclass(frozen=True)
class Expect:
    action: str
    type: str | None = None
    title: tuple[str, ...] = ()
    start: str | None = None
    end: str | None = None
    deadline: str | None = None
    date_from: str | None = None
    date_to: str | None = None
    types: tuple[str, ...] | str | None = None
    query: tuple[str, ...] = ()
    query_from: str | None = None
    query_to: str | None = None
    kind: str | None = None
    ok: bool | None = None
    awaiting: str | None = None


@dataclass(frozen=True)
class Turn:
    text: str
    expect: Expect


@dataclass(frozen=True)
class Case:
    id: str  # номер ровно как в test-cases.md; для раздела 9 — "9:<выражение>"
    turns: tuple[Turn, ...]
    skip: str | None = None
    ref: str | None = None  # раздел 9: строка «Выражение» из таблицы
    note: str = field(default="", compare=False)

    @property
    def section(self) -> str:
        return self.id.split(".")[0].split(":")[0]


def create(type_: str, title: tuple[str, ...] = (), **fields) -> Expect:
    return Expect(action="create_record", type=type_, title=title, **fields)


def listing(date_from: str, date_to: str, types=ALL) -> Expect:
    return Expect(action="list_records", date_from=date_from, date_to=date_to, types=types)


def search(*query: str, **fields) -> Expect:
    return Expect(action="search_records", query=query, **fields)


def one(id_: str, text: str, expect: Expect, **kwargs) -> Case:
    return Case(id=id_, turns=(Turn(text, expect),), **kwargs)


def dialog(id_: str, *turns: tuple[str, Expect], **kwargs) -> Case:
    return Case(id=id_, turns=tuple(Turn(t, e) for t, e in turns), **kwargs)


