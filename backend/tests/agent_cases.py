"""Эталонные кейсы агента — данными (agent-08).

Источник правды для людей — `docs/test-cases.md` (ведёт Маша). Здесь те же кейсы
в виде, который сверяет автотест: номер ровно как в таблице, реплики и ожидание по полям.
`tests/test_agent_cases_sync.py` следит, чтобы номера не разошлись с таблицей.

«Сейчас» во всех кейсах — среда, 21.10.2026 10:00, пояс Europe/Moscow.

Как записывать ожидание (`Expect`) — проверяются только заданные поля, лишние поля
ответа модели тест не роняют:
- `action` — имя действия; несколько допустимых через «|»: "list_records|ask_user";
- `type` — task / meeting / reminder;
- `title`, `query` — ключевые основы слов, без регистра; каждая должна встретиться
  в названии (запросе); альтернативы через «|»: ("КП|коммерческ",);
- `start`, `end`, `deadline`, `date_from`, `date_to` — локальное время пользователя:
  "2026-10-22 10:00" — до минуты; "2026-10-22" — только дата
  (для `start` это ещё и «время не названо», time_given=false); NONE — поля нет;
- `types` — типы списка (tuple), ALL — все типы (None или все три);
- `kind` — у help: help / offtopic;
- `ok` — успешно ли исполнено действие; `awaiting` — ждёт ли ассистент ответа после реплики
  ("answer" или NONE).

Кейс пропускается с причиной (`skip`), если для него ещё нет действия или состояния
разговора. Такие кейсы не удаляются и не переписываются под текущее поведение.
"""

